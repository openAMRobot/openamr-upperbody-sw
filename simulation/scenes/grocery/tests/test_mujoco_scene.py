"""The MuJoCo grocery scene includes the generated robot MJCF unchanged.

Byte level: the file the scene includes is byte-identical to the generator output. Model level: every robot body, joint, actuator
and equality compiles to the same values inside the scene as alone. Needs GROCERY_ROBOT_MJCF (generate.py output).
"""
import hashlib
import re

import numpy as np
import pytest

import compose_mujoco


def test_included_robot_file_is_byte_identical_to_the_generator_output(robot_mjcf, composed):
    out, manifest = composed
    copy = out / manifest["robot_copy"]
    assert copy.read_bytes() == robot_mjcf.read_bytes()
    assert manifest["robot_copy_sha256"] == manifest["robot_source_sha256"] == hashlib.sha256(robot_mjcf.read_bytes()).hexdigest()
    for mesh in (robot_mjcf.parent / "meshes").iterdir():
        assert (out / "meshes" / mesh.name).read_bytes() == mesh.read_bytes(), mesh.name


def test_robot_file_comes_from_the_locked_generator(robot_mjcf):
    """generate.py writes the lock status into the header. A model built without the lock check is not the authoritative model."""
    header = robot_mjcf.read_text().splitlines()[0]
    assert header.startswith("<!-- Generated by simulation/tools/generate.py"), header
    status = re.search(r"\(lock: ([^)]*)\)", header)
    assert status, header
    if status.group(1) == "not checked":
        pytest.fail(f"BLOCKED: {robot_mjcf} was generated without the expansion lock check", pytrace=False)


def test_scene_text_only_includes_the_robot(scene_xml, robot_mjcf):
    text = scene_xml.read_text()
    assert text.count("<include ") == 1 and f'<include file="{robot_mjcf.name}"/>' in text
    robot_names = set(re.findall(r'<body name="([^"]+)"', robot_mjcf.read_text()))
    scene_names = set(re.findall(r'<body name="([^"]+)"', text))
    assert scene_names == {"tote", "target_product"}
    assert not robot_names & scene_names


def _compile(path):
    import mujoco
    return mujoco.MjModel.from_xml_path(str(path))


def test_robot_compiles_identically_inside_the_scene(robot_mjcf, scene_xml):
    import mujoco
    alone, scene = _compile(robot_mjcf), _compile(scene_xml)
    checked = 0
    for b in range(1, alone.nbody):
        name = alone.body(b).name
        s = scene.body(name).id
        for field in ("body_pos", "body_quat", "body_mass", "body_inertia", "body_ipos", "body_iquat"):
            np.testing.assert_array_equal(getattr(alone, field)[b], getattr(scene, field)[s], err_msg=f"{field} {name}")
        assert alone.body(alone.body_parentid[b]).name == scene.body(scene.body_parentid[s]).name
        checked += 1
    for j in range(alone.njnt):
        name = alone.joint(j).name
        s = scene.joint(name).id
        for field in ("jnt_type", "jnt_range", "jnt_axis", "jnt_pos", "jnt_limited"):
            np.testing.assert_array_equal(getattr(alone, field)[j], getattr(scene, field)[s], err_msg=f"{field} {name}")
        assert alone.jnt_qposadr[j] == scene.jnt_qposadr[s]       # the robot's qpos comes first, the scene's free bodies after
        d_a, d_s = alone.jnt_dofadr[j], scene.jnt_dofadr[s]
        for field in ("dof_damping", "dof_armature", "dof_frictionloss"):
            assert getattr(alone, field)[d_a] == getattr(scene, field)[d_s], f"{field} {name}"
    for a in range(alone.nu):
        name = alone.actuator(a).name
        s = scene.actuator(name).id
        for field in ("actuator_gainprm", "actuator_biasprm", "actuator_ctrlrange", "actuator_forcerange", "actuator_trnid"):
            np.testing.assert_array_equal(getattr(alone, field)[a], getattr(scene, field)[s], err_msg=f"{field} {name}")
    for g in range(alone.ngeom):
        name = alone.geom(g).name
        s = scene.geom(name).id
        for field in ("geom_type", "geom_size", "geom_pos", "geom_quat", "geom_friction", "geom_contype", "geom_conaffinity"):
            np.testing.assert_array_equal(getattr(alone, field)[g], getattr(scene, field)[s], err_msg=f"{field} {name}")
    assert alone.neq == scene.neq and alone.nkey == scene.nkey
    np.testing.assert_array_equal(scene.key_qpos[:, :alone.nq], alone.key_qpos)
    for field in ("timestep", "impratio", "cone", "integrator"):
        assert getattr(alone.opt, field) == getattr(scene.opt, field), field
    assert checked == alone.nbody - 1 and alone.nbody > 60
    assert scene.nq == alone.nq + 14 and scene.nu == alone.nu


def test_product_in_the_scene(scene_xml):
    import mujoco
    m = _compile(scene_xml)
    b = m.body("target_product").id
    assert m.body_mass[b] == pytest.approx(0.15)
    g = m.geom("target_product_geom").id
    np.testing.assert_allclose(m.geom_size[g], (0.0175, 0.0175, 0.07))
    assert m.geom_priority[g] == 1 and m.geom_friction[g][0] == 1.0
    assert m.body_mass[m.body("tote").id] == pytest.approx(0.6)


def test_scene_rests(scene_xml):
    """One second from the home keyframe at the pick station: tote and product stay put, the robot stands."""
    import mujoco
    m = _compile(scene_xml)
    d = mujoco.MjData(m)
    mujoco.mj_resetDataKeyframe(m, d, m.key("L1000_home").id)
    mujoco.mj_forward(m, d)
    p0, t0 = d.xpos[m.body("target_product").id].copy(), d.xpos[m.body("tote").id].copy()
    base0 = d.qpos[:3].copy()
    d.ctrl[:] = m.key_ctrl[m.key("L1000_home").id]
    for _ in range(int(1.0 / m.opt.timestep)):
        mujoco.mj_step(m, d)
    assert np.linalg.norm(d.xpos[m.body("target_product").id] - p0) < 1e-3
    assert np.linalg.norm(d.xpos[m.body("tote").id] - t0) < 1e-3
    assert np.linalg.norm(d.qpos[:2] - base0[:2]) < 5e-3 and abs(d.qpos[2] - base0[2]) < 5e-3


