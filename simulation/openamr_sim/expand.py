"""Expand the combined model for a named configuration, the same way Gazebo gets it, and check the hash against the lock.

The expansion is the one the Gazebo simulation uses: combined_robot.xacro with hardware_profile:=gazebo (sim_dynamics auto, so
the OpenArm joints carry <dynamics>). The lift position is never an argument. It is joint state, set later by the backend.

Hash definition, the same as the audits tool digital-twin/phase1/tools/expand_hashes.py (audits be17653):
  SHA-256 of the xacro output, with the banner line "autogenerated by xacro from <path>" removed and every package path of the
  throwaway ament prefix replaced by "$PREFIX/share/<package>".
The lock is mirrored in simulation/expansion_lock.yaml. A computed hash that differs from a locked entry with the same inputs is
an error (LockMismatch). Inputs are: the content digest of the description files that xacro reads (`xacro --deps`, restricted to
this repository, plus combined_robot.xacro), the platform-sw pin, the openarm_description pin, the xacro arguments and the xacro
package version. Files that xacro does not read (tests, READMEs, the engine-override file) are not inputs.
"""
import dataclasses
import hashlib
import os
import pathlib
import shutil
import subprocess
import tempfile

import yaml

REPO = pathlib.Path(__file__).resolve().parents[2]
DESCRIPTION = REPO / "ros2" / "src" / "openamrobot_upperbody_description"
COMBINED = DESCRIPTION / "urdf" / "combined_robot.xacro"
PINS = DESCRIPTION / "config" / "upstream_pins.yaml"
LOCK_MIRROR = REPO / "simulation" / "expansion_lock.yaml"

# Named configurations. Only base_plate varies; the other configuration IDs are the baseline of upperbody_configuration.yaml.
CONFIGURATIONS = {
    "bp000": {"base_plate": "bp000", "hardware_profile": "gazebo"},
    "bp050": {"base_plate": "bp050", "hardware_profile": "gazebo"},
}


class LockMismatch(RuntimeError):
    """The expansion hash differs from the lock for the same inputs."""


class NotLocked(RuntimeError):
    """No lock entry has these inputs. The result cannot be compared and is not a pass."""


@dataclasses.dataclass
class Expansion:
    name: str
    args: dict
    text: str
    sha256: str
    inputs: dict
    lock_status: str
    package_dirs: dict  # package name -> real directory, for mesh resolution


def pins():
    return yaml.safe_load(PINS.read_text())["pins"]


def tree_digest(directory):
    """SHA-256 over the sorted relative paths and file contents of a directory (git-tracked view if available)."""
    directory = pathlib.Path(directory)
    try:
        listed = subprocess.run(["git", "-C", str(directory), "ls-files", "-z", "."], check=True, capture_output=True).stdout
        files = sorted(p for p in listed.decode().split("\0") if p)
    except (subprocess.CalledProcessError, FileNotFoundError):
        files = sorted(str(p.relative_to(directory)) for p in directory.rglob("*") if p.is_file())
    digest = hashlib.sha256()
    for rel in files:
        path = directory / rel
        if not path.is_file():
            continue
        digest.update(rel.encode() + b"\0" + hashlib.sha256(path.read_bytes()).hexdigest().encode() + b"\n")
    return digest.hexdigest()


def deps_digest(prefix, description, xacro_file, args, env):
    """SHA-256 over the description files xacro reads for these arguments, as relative path and content hash."""
    run = subprocess.run(["xacro", "--deps", str(xacro_file), *[f"{k}:={v}" for k, v in args.items()]],
                         capture_output=True, text=True, env=env, check=True)
    root = pathlib.Path(os.path.realpath(description))
    files = {pathlib.Path(xacro_file).resolve()}
    for item in run.stdout.split():
        path = pathlib.Path(os.path.realpath(item))
        if root in path.parents:
            files.add(path)
    digest = hashlib.sha256()
    for path in sorted(files):
        digest.update(str(path.relative_to(root)).encode() + b"\0" + hashlib.sha256(path.read_bytes()).hexdigest().encode() + b"\n")
    return digest.hexdigest()


def xacro_version():
    run = subprocess.run(["dpkg-query", "-W", "-f=${Version}", "ros-jazzy-xacro"], capture_output=True, text=True)
    return run.stdout.strip() or "unknown"


def _make_prefix(prefix, trees):
    index = prefix / "share" / "ament_index" / "resource_index" / "packages"
    index.mkdir(parents=True)
    for tree in trees:
        for manifest in sorted(pathlib.Path(tree).rglob("package.xml")):
            name = manifest.parent.name
            if (prefix / "share" / name).exists():
                continue
            (index / name).touch()
            os.symlink(manifest.parent.resolve(), prefix / "share" / name)


def _normalise(stdout, prefix):
    lines = [line for line in stdout.splitlines(keepends=True) if "autogenerated by xacro from" not in line]
    text = "".join(lines)
    for path in {str(prefix), os.path.realpath(prefix)}:
        text = text.replace(path, "$PREFIX")
    share = prefix / "share"
    for tree in sorted({os.path.realpath(share / d) for d in os.listdir(share) if d != "ament_index"}):
        text = text.replace(tree, "$PREFIX/share/" + os.path.basename(tree))
    return text


def load_lock():
    return yaml.safe_load(LOCK_MIRROR.read_text())


def lock_lookup(inputs, lock=None):
    lock = lock or load_lock()
    for entry in lock["entries"]:
        if all(entry["inputs"].get(k) == v for k, v in inputs.items()):
            return entry
    return None


def expand(name, platform_sw, openarm_description, upstream_extra=(), source_root=REPO, check_lock=True):
    """Expand configuration `name`. platform_sw and openarm_description are checkouts at the pins of upstream_pins.yaml."""
    if shutil.which("xacro") is None:
        raise RuntimeError("BLOCKED: xacro not on PATH (source /opt/ros/jazzy/setup.bash)")
    args = dict(CONFIGURATIONS[name])
    pin = pins()
    for label, path, key in (("platform-sw", platform_sw, "openamr_platform_sw"),
                             ("openarm_description", openarm_description, "openarm_description")):
        head = subprocess.run(["git", "-C", str(path), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
        if head != pin[key]:
            raise RuntimeError(f"BLOCKED: {label} checkout {path} is at {head or 'no commit'}, the pin is {pin[key]}")
    source_root = pathlib.Path(source_root)
    description = source_root / "ros2" / "src" / "openamrobot_upperbody_description"
    with tempfile.TemporaryDirectory() as tmp:
        prefix = pathlib.Path(tmp) / "prefix"
        _make_prefix(prefix, [source_root / "ros2", platform_sw, openarm_description, *upstream_extra])
        package_dirs = {d: os.path.realpath(prefix / "share" / d) for d in os.listdir(prefix / "share") if d != "ament_index"}
        env = dict(os.environ)
        env["AMENT_PREFIX_PATH"] = f"{prefix}:{env.get('AMENT_PREFIX_PATH', '')}"
        inputs = {
            "description_digest": deps_digest(prefix, description, description / "urdf" / "combined_robot.xacro", args, env),
            "platform_sw_pin": pin["openamr_platform_sw"],
            "openarm_description_pin": pin["openarm_description"],
            "base_plate": args["base_plate"],
            "hardware_profile": args["hardware_profile"],
            "xacro_package_version": xacro_version(),
        }
        run = subprocess.run(["xacro", str(description / "urdf" / "combined_robot.xacro"),
                              *[f"{k}:={v}" for k, v in args.items()]], capture_output=True, text=True, env=env)
        if run.returncode != 0:
            raise RuntimeError(f"xacro failed for {name}: {run.stderr.strip()[-2000:]}")
        text = _normalise(run.stdout, prefix)
    sha = hashlib.sha256(text.encode()).hexdigest()
    status = "not checked"
    if check_lock:
        entry = lock_lookup(inputs)
        if entry is not None:
            if entry["sha256"] != sha:
                raise LockMismatch(f"{name}: expansion SHA-256 {sha} differs from the lock {entry['sha256']} for the same inputs")
            status = "matches lock"
        else:
            # The description files differ from every locked commit. The result counts only if the expansion itself is a
            # locked one for the same configuration, pins and xacro build: then the change did not reach the expansion.
            same_args = {k: v for k, v in inputs.items() if k != "description_digest"}
            near = [e for e in load_lock()["entries"] if all(e["inputs"].get(k) == v for k, v in same_args.items())]
            if not any(e["sha256"] == sha for e in near):
                raise NotLocked(f"{name}: no lock entry for inputs {inputs} and the hash {sha} is not locked for this "
                                "configuration. Re-lock in audits first; this is not a pass.")
            status = "hash in lock, inputs changed (description digest not locked; re-lock pending)"
    return Expansion(name=name, args=args, text=text, sha256=sha, inputs=inputs, lock_status=status, package_dirs=package_dirs)
