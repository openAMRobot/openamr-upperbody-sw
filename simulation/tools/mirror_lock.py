"""Write simulation/expansion_lock.yaml from the digital-twin lock in openAMRobot/audits.

The audits repository is internal, so CI here cannot read it. This script copies only the expansion hashes of the combined model and
their inputs (commit, pins, arguments, xacro version). For each locked entry it adds the digest of the description files that
xacro reads at that commit (openamr_sim.expand.deps_digest), taken from `git archive`, so a later checkout that feeds xacro the
same files is the same input. Nothing else from audits is copied.

  source /opt/ros/jazzy/setup.bash
  python3 simulation/tools/mirror_lock.py --lock <audits>/digital-twin/phase1/digital_twin.lock.yaml --audits-commit <sha> \
      --clone <openamr-upperbody-sw clone holding the locked commits> --platform-sw <clone> --openarm-description <clone at pin>
"""
import argparse
import os
import pathlib
import subprocess
import sys
import tempfile

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from openamr_sim.expand import LOCK_MIRROR, _make_prefix, deps_digest  # noqa: E402

DESC = "ros2/src/openamrobot_upperbody_description"


def archive(clone, sha, dest, paths=()):
    dest.mkdir(parents=True)
    tar = subprocess.run(["git", "-C", str(clone), "archive", sha, *paths], check=True, capture_output=True).stdout
    subprocess.run(["tar", "-x", "-C", str(dest)], input=tar, check=True)


def digest_at(clone, sha, platform_sha, platform_clone, openarm, args):
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        archive(clone, sha, tmp / "ub", ["ros2"])
        archive(platform_clone, platform_sha, tmp / "pf")
        prefix = tmp / "prefix"
        _make_prefix(prefix, [tmp / "ub" / "ros2", tmp / "pf", openarm])
        env = dict(os.environ)
        env["AMENT_PREFIX_PATH"] = f"{prefix}:{env.get('AMENT_PREFIX_PATH', '')}"
        desc = tmp / "ub" / DESC
        return deps_digest(prefix, desc, desc / "urdf" / "combined_robot.xacro", args, env)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--lock", required=True)
    parser.add_argument("--audits-commit", required=True)
    parser.add_argument("--clone", required=True)
    parser.add_argument("--platform-sw", required=True)
    parser.add_argument("--openarm-description", required=True)
    parser.add_argument("--out", default=str(LOCK_MIRROR))
    opts = parser.parse_args()
    lock = yaml.safe_load(pathlib.Path(opts.lock).read_text())
    upstream = lock["upstream"]
    xacro = lock["expansions"]["xacro_package_version"]
    head = subprocess.run(["git", "-C", opts.openarm_description, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    if head != upstream["openarm_description"]["sha"]:
        sys.exit(f"openarm_description checkout is at {head}, the lock pins {upstream['openarm_description']['sha']}")
    digests = set()
    entries = []
    for entry in lock["expansions"]["combined_model"]:
        sha = entry["sha"]
        args = {"base_plate": entry["base_plate"], "hardware_profile": entry["hardware_profile"]}
        digest = digest_at(opts.clone, sha, entry["platform_sw_pin"], opts.platform_sw, opts.openarm_description, args)
        digests.add(sha)
        entries.append({
            "source": entry["source"], "commit": sha,
            "inputs": {"description_digest": digest, "platform_sw_pin": entry["platform_sw_pin"],
                       "openarm_description_pin": upstream["openarm_description"]["sha"],
                       "base_plate": entry["base_plate"], "hardware_profile": entry["hardware_profile"],
                       "xacro_package_version": xacro},
            "sha256": entry["sha256"], "bytes": entry["bytes"], "links": entry["links"], "joints": entry["joints"]})
    out = {
        "schema_version": 1,
        "note": ("Mirror of the combined-model expansion hashes of the digital-twin lock. Generated by simulation/tools/mirror_lock.py; "
                 "do not edit by hand. The lock itself is a proposal held in openAMRobot/audits."),
        "lock": {"repository": "openAMRobot/audits", "commit": opts.audits_commit,
                 "file": "digital-twin/phase1/digital_twin.lock.yaml", "lock_date": str(lock["date"]),
                 "normalisation": lock["expansions"]["normalisation"]},
        "entries": entries,
    }
    pathlib.Path(opts.out).write_text("# SPDX-License-Identifier: MIT\n" + yaml.safe_dump(out, sort_keys=False, width=140))
    print(f"{len(entries)} entries, {len(digests)} commits -> {opts.out}")


if __name__ == "__main__":
    main()
