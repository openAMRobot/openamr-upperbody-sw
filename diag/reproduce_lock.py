"""DIAGNOSTIC, scratch branch only, not for merge.

Recompute every expansion hash of the digital-twin lock with the xacro on PATH and compare with the locked values:
the 18 combined-model entries of simulation/expansion_lock.yaml and the 3 base-model entries listed below.
Hash definition as the lock tool: xacro output, banner line removed, the throwaway prefix path replaced by $PREFIX
and every package directory by $PREFIX/share/<package>. Sources come from `git archive <sha>` of local clones.
"""
import argparse
import hashlib
import json
import os
import pathlib
import subprocess
import sys
import tempfile

import yaml

COMBINED = "ros2/src/openamrobot_upperbody_description/urdf/combined_robot.xacro"
PINS = "ros2/src/openamrobot_upperbody_description/config/upstream_pins.yaml"
BASE = "ros2/src/openamrobot_description/urdf/robo_urdf.urdf.xacro"
BASE_LOCK = [
    ("07417783bb602c233f7011599dc12e4d81e38a04", "6d6b2bf35b1c3c1ffe09e1ce9b348534cf0220ce3bd26a26d64c63cd0b825fb0", 38539),
    ("acc427d7ad9b1f90591011f1824d470a9a3fd883", "9eaeef509707b85ddc7e9a06eb8a6556ebe861a9d9fdfcd9de03c21a0b7a2cda", 47736),
    ("9be73229ad60a41a9ba1419d15527199f58c5b41", "84a1f1dd4d13f2a9e3c490f4ae548ded4753a1bd17eb98df2863713de296759f", 40361),
]


def archive(clone, sha, dest):
    dest.mkdir(parents=True)
    tar = subprocess.run(["git", "-C", str(clone), "archive", sha], check=True, capture_output=True).stdout
    subprocess.run(["tar", "-x", "-C", str(dest)], input=tar, check=True)


def make_prefix(prefix, trees):
    index = prefix / "share" / "ament_index" / "resource_index" / "packages"
    index.mkdir(parents=True)
    for tree in trees:
        for manifest in sorted(pathlib.Path(tree).rglob("package.xml")):
            name = manifest.parent.name
            if (prefix / "share" / name).exists():
                continue
            (index / name).touch()
            os.symlink(manifest.parent, prefix / "share" / name)


def expand(prefix, xacro_file, args):
    env = dict(os.environ)
    env["AMENT_PREFIX_PATH"] = f"{prefix}:{env.get('AMENT_PREFIX_PATH', '')}"
    run = subprocess.run(["xacro", str(xacro_file), *[f"{k}:={v}" for k, v in args.items()]], capture_output=True, text=True, env=env)
    if run.returncode != 0:
        raise RuntimeError(run.stderr[-2000:])
    text = "".join(line for line in run.stdout.splitlines(keepends=True) if "autogenerated by xacro from" not in line)
    for path in {str(prefix), os.path.realpath(prefix)}:
        text = text.replace(path, "$PREFIX")
    for tree in sorted({os.path.realpath(prefix / "share" / d) for d in os.listdir(prefix / "share") if d != "ament_index"}):
        text = text.replace(tree, "$PREFIX/share/" + os.path.basename(tree))
    return text


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--lock", required=True)
    p.add_argument("--upperbody", required=True)
    p.add_argument("--platform", required=True)
    p.add_argument("--openarm-description", required=True)
    p.add_argument("--openarm-ros2", required=True)
    p.add_argument("--label", required=True)
    p.add_argument("--out", required=True)
    o = p.parse_args()
    lock = yaml.safe_load(pathlib.Path(o.lock).read_text())
    rows, bad = [], 0
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        trees = {}

        def tree(clone, sha, tag):
            if sha not in trees:
                trees[sha] = tmp / f"{tag}-{sha[:7]}"
                archive(clone, sha, trees[sha])
            return trees[sha]

        prefixes = {}
        for e in lock["entries"]:
            sha, inp = e["commit"], e["inputs"]
            ub = tree(o.upperbody, sha, "ub")
            pin = yaml.safe_load((ub / PINS).read_text())["pins"]
            if sha not in prefixes:
                prefixes[sha] = tmp / f"prefix-{sha[:7]}"
                make_prefix(prefixes[sha], [ub, tree(o.platform, pin["openamr_platform_sw"], "pf"), o.openarm_description, o.openarm_ros2])
            text = expand(prefixes[sha], ub / COMBINED, {"base_plate": inp["base_plate"], "hardware_profile": inp["hardware_profile"]})
            got = hashlib.sha256(text.encode()).hexdigest()
            ok = got == e["sha256"] and len(text.encode()) == e["bytes"] and text.count("<link ") == e["links"] and text.count("<joint ") == e["joints"]
            bad += not ok
            rows.append({"group": "combined_model", "commit": sha, "base_plate": inp["base_plate"], "profile": inp["hardware_profile"],
                         "locked": e["sha256"], "computed": got, "bytes": len(text.encode()), "identical": ok})
        for sha, locked, nbytes in BASE_LOCK:
            pf = tree(o.platform, sha, "pf")
            prefix = tmp / f"prefix-p-{sha[:7]}"
            make_prefix(prefix, [pf])
            text = expand(prefix, pf / BASE, {})
            got = hashlib.sha256(text.encode()).hexdigest()
            ok = got == locked and len(text.encode()) == nbytes
            bad += not ok
            rows.append({"group": "base_model", "commit": sha, "locked": locked, "computed": got, "bytes": len(text.encode()), "identical": ok})
    result = {"label": o.label, "identical": sum(r["identical"] for r in rows), "total": len(rows), "rows": rows}
    pathlib.Path(o.out).write_text(json.dumps(result, indent=1))
    for r in rows:
        print(f"{o.label} {r['group']:14} {r['commit'][:7]} {r.get('base_plate', '-'):5} {r.get('profile', '-'):6} "
              f"locked {r['locked'][:12]} computed {r['computed'][:12]} {'IDENTICAL' if r['identical'] else 'DIFFERENT'}")
    print(f"{o.label}: {result['identical']} of {result['total']} identical")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
